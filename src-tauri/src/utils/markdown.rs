        // 內聯記憶索引：帶入一筆 bullet，應出現在產出檔中
        let bullets = memory_bullets(&[(
            "test-mem.md".to_string(),
            "測試記憶".to_string(),
            "一句 hook".to_string(),
        )]);

        // AGENTS.md：含專案指針、保留標頭、引用 codex 錨點、內聯記憶索引
        let agents = build_agents_md("projects/foo", &bullets);
        assert!(agents.starts_with("# AGENTS.md"));
        assert!(agents.contains("AMAGI-VAULT-PROJECT:BEGIN"));
        assert!(agents.contains("projects/foo/"));
        assert!(agents.contains("~/.codex/AGENTS.md"));
        // 開場讀取須先讀 handoff.md（當前狀態活頁）——交接改專案活頁後的指針同步
        assert!(agents.contains("handoff.md"), "專案指針應指示先讀 handoff.md");
        // 記憶改內聯：條目直接出現在檔中（非僅指向 agent/memory）
        assert!(agents.contains("本專案記憶"));
        assert!(agents.contains("[測試記憶](test-mem.md)"));

        // 空索引 → 顯示「（尚無）」
        let agents_empty = build_agents_md("projects/foo", "");
        assert!(agents_empty.contains("（尚無）"));

        // 專案 CLAUDE.md（Some）：含指針、引用 claude 錨點、內聯記憶、工作流薄錨
        let proj_claude = build_claude_md(Some("projects/foo"), &bullets);
        assert!(proj_claude.contains("AMAGI-VAULT-PROJECT:BEGIN"));
        assert!(proj_claude.contains("~/.claude/CLAUDE.md"));
        assert!(proj_claude.contains("[測試記憶](test-mem.md)"));
        // 專案層應帶工作流薄錨（指向軌跡檔）
        assert!(proj_claude.contains("開發工作流"), "專案 CLAUDE.md 應帶工作流薄錨");
        assert!(proj_claude.contains(".amagi/workflow-state.md"), "專案薄錨應指向軌跡檔");

        // 全域 CLAUDE.md（None）：絕不帶專案指針，也不帶工作流薄錨（doctrine 本體在全域，避免重複）
